"use strict";
const fs = require("fs"), path = require("path");
const root = path.resolve(__dirname, "..");
const source = fs.readFileSync(path.join(root, "server/src/content/noticeReactions.js"), "utf8");
const target = path.join(root, "miniprogram/utils/noticeReactions.js");
const generated = "// Generated by tools/generate-notice-reactions.js; edit server/src/content/noticeReactions.js.\n" + source;
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== generated) throw new Error("Notice reaction catalog is out of date; run node tools/generate-notice-reactions.js");
} else fs.writeFileSync(target, generated);
console.log("notice reaction compatibility catalog " + (process.argv.includes("--check") ? "verified" : "generated"));
