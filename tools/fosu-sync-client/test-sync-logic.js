const assert = require("assert");
const fs = require("fs");
const path = require("path");

// 1. 模拟前端命令生成逻辑以进行测试
function getRecommendGrades(term) {
  var match = term.match(/^(\d{4})/);
  if (match) {
    var startYear = parseInt(match[1], 10);
    var grades = [];
    for (var i = 0; i < 5; i++) {
      grades.push(startYear - i);
    }
    return grades.join(",");
  }
  return "2026,2025,2024,2023,2022";
}

function getFreshmanGrade(term) {
  var match = term.match(/^(\d{4})/);
  return match ? match[1] : "2026";
}

function getAutoGeneratedVersion(term) {
  return (term || "2026-2027-1").replace(/-/g, "") + "-test-version";
}

function generateFrontendCommand(opts) {
  var term = opts.term || "2026-2027-1";
  var startDate = opts.startDate || "2026-09-01";
  var source = opts.source || "local-campus";
  var note = opts.note || (term + " 测试同步");
  
  var scopes = opts.scopes || [];
  var scopesStr = scopes.join(",");
  
  var gradesMode = opts.gradesMode || "recommend";
  var gradesVal = "";
  if (gradesMode === "recommend") {
    gradesVal = getRecommendGrades(term);
  } else if (gradesMode === "freshman") {
    gradesVal = getFreshmanGrade(term);
  } else if (gradesMode === "custom") {
    gradesVal = (opts.gradesCustom || "").trim();
  }
  
  var collegeCodes = (opts.collegeCodes || "").trim();
  var majorCodes = (opts.majorCodes || "").trim();
  var concurrency = opts.concurrency || "1";
  var delay = opts.delay || "900";
  
  var isDebugMode = opts.isDebugMode || false;
  var output = isDebugMode ? "./staging/debug-" + term + ".json" : "./staging/" + term + "-full.json";
  
  var hasClassSchedules = scopes.indexOf("classSchedules") >= 0;
  
  var envVars = [];
  if (hasClassSchedules) {
    envVars.push({ name: "SYNC_CLASS_SCOPE", val: "all" });
  }
  if (gradesVal) {
    envVars.push({ name: "SYNC_CLASS_GRADES", val: gradesVal });
  }
  if (scopesStr) {
    envVars.push({ name: "SYNC_INCLUDE_SCOPES", val: scopesStr });
  }
  if (concurrency) {
    envVars.push({ name: "SYNC_CLASS_MAX_CONCURRENCY", val: concurrency });
  }
  if (delay) {
    envVars.push({ name: "SYNC_CLASS_REQUEST_DELAY_MS", val: delay });
  }
  if (collegeCodes) {
    envVars.push({ name: "SYNC_CLASS_COLLEGE_CODES", val: collegeCodes });
  }
  if (majorCodes) {
    envVars.push({ name: "SYNC_CLASS_MAJOR_CODES", val: majorCodes });
  }
  
  var cliArgs = [
    "--term=" + term,
    "--start=" + startDate,
    "--output=" + output,
    "--include=" + scopesStr
  ];
  if (hasClassSchedules) {
    cliArgs.push("--class-scope=all");
  }
  if (gradesVal) {
    cliArgs.push("--grades=" + gradesVal);
  }
  if (concurrency) {
    cliArgs.push("--concurrency=" + concurrency);
  }
  if (delay) {
    cliArgs.push("--delay-ms=" + delay);
  }
  if (collegeCodes) {
    cliArgs.push("--college-codes=" + collegeCodes);
  }
  if (majorCodes) {
    cliArgs.push("--major-codes=" + majorCodes);
  }
  if (opts.forceRefresh) {
    cliArgs.push("--force-refresh");
  }
  
  var cliArgsStr = cliArgs.join(" ");
  var commandText = "";
  var shell = opts.shell || "powershell";
  var projectDirWin = "C:\\Users\\Katelya\\Documents\\VScode\\FosuClass";
  var projectDirBash = "/c/Users/Katelya/Documents/VScode/FosuClass";
  
  if (shell === "cmd") {
    commandText += "cd /d " + projectDirWin + "\n";
    envVars.forEach(function(ev) {
      commandText += "set " + ev.name + "=" + ev.val + "\n";
    });
    commandText += "npm run sync:" + source + " -- " + cliArgsStr;
  } else if (shell === "powershell") {
    commandText += "cd " + projectDirWin + "\n";
    envVars.forEach(function(ev) {
      commandText += '$env:' + ev.name + '="' + ev.val + '"\n';
    });
    commandText += "npm run sync:" + source + " -- " + cliArgsStr;
  } else {
    // bash
    commandText += "cd " + projectDirBash + "\n";
    envVars.forEach(function(ev) {
      commandText += ev.name + "=" + ev.val + " \\\n";
    });
    commandText += "npm run sync:" + source + " -- " + cliArgsStr;
  }
  
  return {
    commandText: commandText,
    cliArgsStr: cliArgsStr,
    envVars: envVars
  };
}

// 模拟后台对 staging classSchedules 为 0 时的防呆熔断
function simulateStagingPublishValidation(d, isClassChecked) {
  if (d.counts.classScheduleCount === 0 && isClassChecked) {
    return {
      allowed: false,
      reason: "熔断拦截: 本次上传的行政班课表数为 0，但您的同步范围中勾选了行政班。为了防止发布空包清空小程序线上数据，正式发布已被禁用！"
    };
  }
  return { allowed: true };
}

// =================== 运行测试 ===================
async function runTests() {
  console.log("🚀 开始执行同步中心深度修复与优化逻辑验证...");

  // 测试 1: 测试 includeScopes 勾选变化后，命令实时变化
  console.log("🧪 [测试 1] 测试 includeScopes 勾选变化后，命令相应改变...");
  const cmdAll = generateFrontendCommand({
    term: "2025-2026-2",
    scopes: ["classSchedules", "teacherSchedules", "classroomSchedules", "courses"]
  });
  assert.ok(cmdAll.cliArgsStr.includes("--include=classSchedules,teacherSchedules,classroomSchedules,courses"));

  const cmdSubset = generateFrontendCommand({
    term: "2025-2026-2",
    scopes: ["teacherSchedules", "classroomSchedules"]
  });
  assert.ok(cmdSubset.cliArgsStr.includes("--include=teacherSchedules,classroomSchedules"));
  assert.ok(!cmdSubset.cliArgsStr.includes("classSchedules"));
  console.log("   ✅ [测试 1] 通过!");

  // 测试 2: 测试勾选行政班课表时，命令包含 SYNC_CLASS_SCOPE=all / --class-scope=all
  console.log("🧪 [测试 2] 测试勾选行政班课表时，生成全校同步控制参数...");
  const cmdWithClass = generateFrontendCommand({
    term: "2025-2026-2",
    scopes: ["classSchedules"]
  });
  assert.ok(cmdWithClass.cliArgsStr.includes("--class-scope=all"));
  assert.ok(cmdWithClass.commandText.includes("SYNC_CLASS_SCOPE"));
  assert.ok(cmdWithClass.commandText.includes("all"));

  const cmdNoClass = generateFrontendCommand({
    term: "2025-2026-2",
    scopes: ["teacherSchedules"]
  });
  assert.ok(!cmdNoClass.cliArgsStr.includes("--class-scope"));
  assert.ok(!cmdNoClass.commandText.includes("SYNC_CLASS_SCOPE"));
  console.log("   ✅ [测试 2] 通过!");

  // 测试 3: 测试 Windows CMD / PowerShell / Bash 三种命令行格式
  console.log("🧪 [测试 3] 测试 CMD, PowerShell, Bash 三种 Shell 的环境变量语法区别...");
  const cmdPowershell = generateFrontendCommand({
    term: "2025-2026-2",
    scopes: ["classSchedules"],
    shell: "powershell"
  });
  assert.ok(cmdPowershell.commandText.includes('$env:SYNC_CLASS_SCOPE="all"'));
  assert.ok(!cmdPowershell.commandText.includes('set SYNC_CLASS_SCOPE'));

  const cmdCmd = generateFrontendCommand({
    term: "2025-2026-2",
    scopes: ["classSchedules"],
    shell: "cmd"
  });
  assert.ok(cmdCmd.commandText.includes('set SYNC_CLASS_SCOPE=all'));
  assert.ok(!cmdCmd.commandText.includes('$env:'));

  const cmdBash = generateFrontendCommand({
    term: "2025-2026-2",
    scopes: ["classSchedules"],
    shell: "bash"
  });
  assert.ok(cmdBash.commandText.includes('SYNC_CLASS_SCOPE=all \\'));
  assert.ok(!cmdBash.commandText.includes('set '));
  console.log("   ✅ [测试 3] 通过!");

  // 测试 4: 测试 classSchedules = 0 且勾选行政班时，后台防呆熔断禁用发布
  console.log("🧪 [测试 4] 测试 classSchedules=0 且勾选行政班课表时，防呆熔断是否触发...");
  const badStaging = {
    term: "2025-2026-2",
    counts: {
      classScheduleCount: 0,
      teacherScheduleCount: 15,
      classroomScheduleCount: 22
    }
  };
  const resBad = simulateStagingPublishValidation(badStaging, true);
  assert.strictEqual(resBad.allowed, false);
  assert.ok(resBad.reason.includes("熔断拦截"));

  // 如果没有勾选行政班（只更新公共资源模式），classScheduleCount 为 0 是被允许的
  const resGood = simulateStagingPublishValidation(badStaging, false);
  assert.strictEqual(resGood.allowed, true);
  console.log("   ✅ [测试 4] 通过!");

  // 测试 5: 测试 sync.js 在 local-campus 且没指定过滤条件时的活跃年级推算
  console.log("🧪 [测试 5] 测试 sync.js 默认活跃年级推荐逻辑...");
  const grades_2025_2 = getRecommendGrades("2025-2026-2");
  assert.strictEqual(grades_2025_2, "2025,2024,2023,2022,2021");

  const grades_2026_1 = getRecommendGrades("2026-2027-1");
  assert.strictEqual(grades_2026_1, "2026,2025,2024,2023,2022");
  console.log("   ✅ [测试 5] 通过!");

  console.log("🧪 [测试 6] 测试强制全量刷新参数进入命令...");
  const cmdForce = generateFrontendCommand({
    term: "2025-2026-2",
    scopes: ["classSchedules", "teacherSchedules", "classroomSchedules", "courseSchedules", "classrooms", "teachers", "courses"],
    forceRefresh: true,
    shell: "powershell"
  });
  assert.ok(cmdForce.cliArgsStr.includes("--force-refresh"));
  assert.ok(cmdForce.cliArgsStr.includes("--class-scope=all"));
  assert.ok(cmdForce.commandText.includes("cd C:\\Users\\Katelya\\Documents\\VScode\\FosuClass"));
  console.log("   ✅ [测试 6] 通过!");

  console.log("\n🎉 所有同步向导与拦截发布逻辑的断言测试全部通过！");
}

runTests().catch(err => {
  console.error("❌ 测试执行中出现未捕获异常:", err);
  process.exit(1);
});
