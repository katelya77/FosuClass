"use strict";

function buildCategory(category, title, type, contents, offset = 0) {
  return contents.map((content, index) => Object.freeze({
    id: `daily_${category}_${String(offset + index + 1).padStart(3, "0")}`,
    category,
    title,
    content,
    type,
  }));
}

function composeContents(contexts, actions) {
  return contexts.flatMap((context) => actions.map((action) => `${context}，${action}`));
}

